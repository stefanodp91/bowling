// npm run notices: writes THIRD_PARTY_NOTICES.md from the licence fields and files of every
// production dependency (wiki/release/open-source.md, rule 2).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT } from '../lib/gate.mjs';
import { licenceTexts, productionDependencies, readLock } from './production-deps.mjs';

export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.md';

/** The heading of a dependency in the notices: what check-notices looks for. */
export const headingOf = (dep) => `## ${dep.name} ${dep.version}`;

const THANKS = [
  'Thanks to Simone De Vittorio, author of [Reactylon](https://www.reactylon.com), for making',
  'React on Babylon.js possible: the game and its model catalogue are React components rendering',
  'Babylon.js scenes because of that work.',
].join('\n');

export function renderNotices(root = REPO_ROOT) {
  const deps = productionDependencies(readLock(root));
  const sections = deps.map((dep) => {
    const texts = licenceTexts(root, dep);
    const body = texts.length === 0
      ? `License: ${dep.license} (declared in its package.json; the package ships no licence file).`
      : [`License: ${dep.license}`, ...texts.map((t) => `### ${t.file}\n\n\`\`\`text\n${t.text}\n\`\`\``)].join('\n\n');
    return `${headingOf(dep)}\n\n${body}`;
  });
  return [
    '# Third-party notices',
    '',
    'Generated by `npm run notices` from `package-lock.json` and each package\'s own licence files.',
    'These are the packages the game ships (its production dependencies, with the peers they need).',
    'Do not edit by hand.',
    '',
    THANKS,
    '',
    ...sections.flatMap((s) => [s, '']),
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(REPO_ROOT, NOTICES_FILE), renderNotices());
  console.log(`${NOTICES_FILE} written`);
}
