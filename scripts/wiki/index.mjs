// npm run wiki:index [-- --check]: regenerates wiki/index.md (wiki/method/wiki-tooling.md, rule 2).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { finding, REPO_ROOT, runGate, withTempDir } from '../lib/gate.mjs';
import { INDEX_PAGE, loadWiki, specPages, wikiDirOf } from './parse.mjs';
import { writeFixtureWiki } from './fixture.mjs';

const HEADER = `# Wiki index

Generated by \`npm run wiki:index\` (written by hand in round zero, same format). Do not edit by hand
once the script exists.
`;
const NONE = '_None yet._';

/** Spec pages in topological order of depends_on; ties broken by path, in code-point order. */
export function buildOrder(pages) {
  const specs = specPages(pages);
  const done = new Set();
  const ordered = [];
  while (ordered.length < specs.length) {
    const next = specs.find((p) => !done.has(p.path) && (p.frontMatter.depends_on ?? []).every((d) => done.has(d)));
    if (next === undefined) {
      const stuck = specs.filter((p) => !done.has(p.path)).map((p) => p.path);
      throw new Error(`depends_on has a cycle or a missing page among: ${stuck.join(', ')}`);
    }
    done.add(next.path);
    ordered.push(next);
  }
  return ordered;
}

export function renderIndex(pages) {
  const link = (p) => `[${p.path}](${p.path}) — ${p.frontMatter.title}`;
  const byType = (type) => pages.filter((p) => p.frontMatter?.type === type);
  const list = (items) => (items.length === 0 ? NONE : items.map((p) => `- ${link(p)}`).join('\n'));
  const specs = buildOrder(pages).map((p, i) => `${i + 1}. ${link(p)} · \`${p.frontMatter.status}\``);
  return `${HEADER}
## Specification, in build order

${specs.join('\n')}

## Concepts

${list(byType('concept'))}

## Records

${list(byType('record'))}
`;
}

export function indexFindings(root) {
  const wikiDir = wikiDirOf(root);
  const expected = renderIndex(loadWiki(wikiDir));
  const actual = readFileSync(join(wikiDir, INDEX_PAGE), 'utf8');
  return actual === expected ? [] : [finding('wiki/index.md', undefined, 'stale: run npm run wiki:index')];
}

export const indexSelftest = () =>
  withTempDir((dir) => {
    writeFixtureWiki(dir);
    writeFileSync(join(dir, 'wiki/index.md'), renderIndex(loadWiki(wikiDirOf(dir))).replace('`planned`', '`built`'));
    return indexFindings(dir);
  });

const isMain = import.meta.url === `file://${process.argv[1]}`;
if (isMain && (process.argv.includes('--check') || process.argv.includes('--selftest'))) {
  runGate('wiki:index --check', {
    check: indexFindings,
    selftest: indexSelftest,
  });
} else if (isMain) {
  const wikiDir = wikiDirOf(REPO_ROOT);
  writeFileSync(join(wikiDir, INDEX_PAGE), renderIndex(loadWiki(wikiDir)));
  console.log('wiki/index.md regenerated');
}
